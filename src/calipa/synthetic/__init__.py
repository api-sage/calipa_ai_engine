"""Synthetic GL data shaped exactly like the FCY API, with known planted problems.

Used for tests and for the P2 evals. Every transfer follows the posting pattern seen
on live data; planted anomalies change one thing about it, and each one is labelled
with the engine exceptions it must produce. Generation is fully determined by the
seed, so a dataset can be regenerated byte for byte.
"""

from __future__ import annotations

import random
from dataclasses import dataclass, replace
from datetime import UTC, date, datetime, time, timedelta
from decimal import Decimal
from enum import StrEnum
from typing import Any
from uuid import UUID
from zoneinfo import ZoneInfo

from calipa.analyst.schema import RootCause
from calipa.engine.contract import ExceptionType, RateQuote
from calipa.money import Currency, Money, canonical_decimal
from calipa.reference import AccountCatalog, AccountRole, Tariff

E = ExceptionType


class Anomaly(StrEnum):
    CLEAN = "clean"
    FEE_VAT_LEGS_MISSING = "fee_vat_legs_missing"  # like live transfer ...0001
    FEE_AMOUNT_WRONG = "fee_amount_wrong"
    VAT_AMOUNT_WRONG = "vat_amount_wrong"
    FX_RATE_WRONG = "fx_rate_wrong"
    ROUNDING_OFF_BY_ONE = "rounding_off_by_one"
    DUPLICATE_INSTRUCTION = "duplicate_instruction"  # like live ...0001 / ...0002
    DUPLICATE_ENTRY = "duplicate_entry"
    DEST_CURRENCY_FEE_LEGS = "dest_currency_fee_legs"  # like live transfer ...0002
    PAYOUT_LEG_MISSING = "payout_leg_missing"


EXPECTED: dict[Anomaly, frozenset[ExceptionType]] = {
    Anomaly.CLEAN: frozenset(),
    Anomaly.FEE_VAT_LEGS_MISSING: frozenset(
        {E.FEE_LEG_MISSING, E.VAT_LEG_MISSING, E.TRANSIENT_RESIDUAL}
    ),
    Anomaly.FEE_AMOUNT_WRONG: frozenset({E.FEE_AMOUNT_MISMATCH, E.TRANSIENT_RESIDUAL}),
    Anomaly.VAT_AMOUNT_WRONG: frozenset({E.VAT_AMOUNT_MISMATCH, E.TRANSIENT_RESIDUAL}),
    Anomaly.FX_RATE_WRONG: frozenset({E.FX_CONVERSION_MISMATCH}),
    Anomaly.ROUNDING_OFF_BY_ONE: frozenset({E.ROUNDING_DIFFERENCE}),
    # Labelled on the second transfer of the pair; the first one is clean.
    Anomaly.DUPLICATE_INSTRUCTION: frozenset({E.DUPLICATE_INSTRUCTION_CANDIDATE}),
    Anomaly.DUPLICATE_ENTRY: frozenset(
        {E.DUPLICATE_ENTRY, E.FEE_AMOUNT_MISMATCH, E.TRANSIENT_RESIDUAL}
    ),
    Anomaly.DEST_CURRENCY_FEE_LEGS: frozenset(
        {E.FEE_VAT_IN_BOTH_CURRENCIES, E.ENTRY_DIRECTION_INCONSISTENT}
    ),
    Anomaly.PAYOUT_LEG_MISSING: frozenset({E.STRUCTURE_INCOMPLETE}),
}

# The root cause P2 should rank first for each planted anomaly. A missing payout leg
# has no visible cause in the GL alone (switch logs would show one), so an honest
# "unexplained" is as right as a timing hypothesis.
EXPECTED_ROOT_CAUSE: dict[Anomaly, frozenset[RootCause]] = {
    Anomaly.FEE_VAT_LEGS_MISSING: frozenset({"fee_or_vat_leg_missing"}),
    Anomaly.FEE_AMOUNT_WRONG: frozenset({"tariff_applied_mismatch"}),
    Anomaly.VAT_AMOUNT_WRONG: frozenset({"tariff_applied_mismatch"}),
    Anomaly.FX_RATE_WRONG: frozenset({"fx_rate_applied_mismatch"}),
    Anomaly.ROUNDING_OFF_BY_ONE: frozenset({"rounding_difference"}),
    Anomaly.DUPLICATE_INSTRUCTION: frozenset({"duplicate_customer_instruction"}),
    Anomaly.DUPLICATE_ENTRY: frozenset({"duplicate_posting_same_instruction"}),
    Anomaly.DEST_CURRENCY_FEE_LEGS: frozenset({"fee_or_vat_leg_duplicated_across_ccy"}),
    Anomaly.PAYOUT_LEG_MISSING: frozenset({"unexplained", "timing_cutoff_difference"}),
}

# Rates recorded from the live API on 2026-10-26 (identical on 2026-10-25).
RECORDED_RATES: dict[tuple[Currency, Currency], Decimal] = {
    (Currency(a), Currency(b)): Decimal(r)
    for a, b, r in [
        ("EUR", "GBP", "0.8724"), ("EUR", "NGN", "1580.48135373"), ("EUR", "USD", "1.1845"),
        ("GBP", "EUR", "1.14626318"), ("GBP", "NGN", "1810.06486117"),
        ("GBP", "USD", "1.35774874"), ("NGN", "EUR", "0.00063272"),
        ("NGN", "GBP", "0.00055247"), ("NGN", "USD", "0.00074717"),
        ("USD", "EUR", "0.84423808"), ("USD", "GBP", "0.7365133"),
        ("USD", "NGN", "1338.380059"),
    ]
}  # fmt: skip

PAIRS: tuple[tuple[Currency, Currency], ...] = (
    (Currency.GBP, Currency.USD),
    (Currency.USD, Currency.GBP),
    (Currency.EUR, Currency.USD),
    (Currency.USD, Currency.NGN),
    (Currency.GBP, Currency.NGN),
    (Currency.EUR, Currency.GBP),
)


@dataclass(frozen=True, slots=True)
class PlantedTransfer:
    transfer_id: UUID
    reference: str
    anomaly: Anomaly
    expected: frozenset[ExceptionType]
    related_transfer_id: UUID | None = None


@dataclass(frozen=True, slots=True)
class Dataset:
    seed: int
    day: date
    entries: list[dict[str, Any]]  # API-shaped; amounts as decimal strings
    labels: list[PlantedTransfer]
    rates: list[RateQuote]


@dataclass(frozen=True, slots=True)
class _Spec:
    src: Currency
    dst: Currency
    principal: Money
    customer: str
    beneficiary: str
    at: datetime


class _Builder:
    def __init__(self, seed: int, day: date, tz: ZoneInfo, catalog: AccountCatalog, tariff: Tariff):
        self.rng = random.Random(seed)  # noqa: S311 - test data, not security
        self.day, self.tz, self.tariff = day, tz, tariff
        self.transient = catalog.account_for(AccountRole.TRANSIENT)
        self.fee_account = catalog.account_for(AccountRole.FEE_INCOME)
        self.vat_account = catalog.account_for(AccountRole.VAT)
        self.reserved = set(catalog.roles)
        self.entries: list[dict[str, Any]] = []
        self.labels: list[PlantedTransfer] = []
        self.sequence = 0

    def uuid(self) -> UUID:
        return UUID(int=self.rng.getrandbits(128), version=4)

    def account(self) -> str:
        while True:
            number = f"{self.rng.randrange(10**10):010d}"
            if number not in self.reserved:
                return number

    def moment(self) -> datetime:
        local = datetime.combine(self.day, time(1, 0), self.tz) + timedelta(
            seconds=self.rng.randrange(21 * 3600)
        )
        return local.astimezone(UTC).replace(microsecond=0)

    def rate(self, a: Currency, b: Currency) -> Decimal:
        return Decimal(1) if a is b else RECORDED_RATES[(a, b)]

    def q(self, value: Decimal, currency: Currency) -> Money:
        return Money(value, currency).quantize(self.tariff.rounding)

    def transfer(
        self,
        anomaly: Anomaly,
        *,
        clone_of: _Spec | None = None,
        related: UUID | None = None,
    ) -> tuple[_Spec, UUID]:
        self.sequence += 1
        if clone_of is None:
            src, dst = self.rng.choice(PAIRS)
            spec = _Spec(
                src=src,
                dst=dst,
                principal=Money(Decimal(self.rng.randrange(500, 500_000)).scaleb(-2), src),
                customer=self.account(),
                beneficiary=self.account(),
                at=self.moment(),
            )
        else:
            spec = replace(
                clone_of, at=clone_of.at + timedelta(seconds=self.rng.randrange(10, 120))
            )
        src, dst, principal = spec.src, spec.dst, spec.principal
        charge = self.q(
            self.tariff.flat_charge.amount * self.rate(self.tariff.flat_charge.currency, src), src
        )
        vat = self.q(principal.amount * self.tariff.vat_rate, src)
        fx = self.rate(src, dst)
        if anomaly is Anomaly.FX_RATE_WRONG:
            fx = fx * Decimal("1.01")
        payout = self.q(principal.amount * fx, dst)
        if anomaly is Anomaly.ROUNDING_OFF_BY_ONE:
            payout = Money(payout.amount + Decimal(1).scaleb(-dst.minor_units), dst)
        funding = principal + charge + vat
        posted_charge, posted_vat = charge, vat
        if anomaly is Anomaly.FEE_AMOUNT_WRONG:
            posted_charge = Money(charge.amount + Decimal("0.50"), src)
        if anomaly is Anomaly.VAT_AMOUNT_WRONG:
            posted_vat = Money(vat.amount + Decimal("0.40"), src)

        transfer_id = self.uuid()
        at = spec.at
        local = at.astimezone(self.tz)
        reference = f"{local:%Y%m%d%H%M%S}{self.rng.randrange(10**10):010d}{self.sequence:06d}"
        legs: list[tuple[str, str, str, Money]] = [
            (spec.customer, self.transient, "CREDIT", funding),
        ]
        if anomaly is not Anomaly.PAYOUT_LEG_MISSING:
            legs.append((self.transient, spec.beneficiary, "DEBIT", payout))
        if anomaly is not Anomaly.FEE_VAT_LEGS_MISSING:
            legs.append((self.transient, self.fee_account, "DEBIT", posted_charge))
            legs.append((self.transient, self.vat_account, "DEBIT", posted_vat))
        if anomaly is Anomaly.DUPLICATE_ENTRY:
            legs.append((self.transient, self.fee_account, "DEBIT", posted_charge))
        if anomaly is Anomaly.DEST_CURRENCY_FEE_LEGS:
            # As on live transfer ...0002: the charges again in the destination currency,
            # with entryType CREDIT although the transient account is debited.
            dest_charge = self.q(
                self.tariff.flat_charge.amount * self.rate(self.tariff.flat_charge.currency, dst),
                dst,
            )
            dest_vat = self.q(payout.amount * self.tariff.vat_rate, dst)
            legs.append((self.transient, self.fee_account, "CREDIT", dest_charge))
            legs.append((self.transient, self.vat_account, "CREDIT", dest_vat))

        offset = 0
        for debited, credited, entry_type, amount in legs:
            self.entries.append(
                {
                    "id": str(self.uuid()),
                    "transferId": str(transfer_id),
                    "externalReference": reference,
                    "debitedAccount": debited,
                    "creditedAccount": credited,
                    "entryType": entry_type,
                    "currency": amount.currency.value,
                    "amount": canonical_decimal(amount.amount),
                    "createdAt": (at + timedelta(seconds=offset))
                    .isoformat()
                    .replace("+00:00", "Z"),
                }
            )
            offset += self.rng.choice((0, 0, 1, 2))  # same-second legs are common
        self.labels.append(
            PlantedTransfer(transfer_id, reference, anomaly, EXPECTED[anomaly], related)
        )
        return spec, transfer_id


def generate(
    seed: int,
    *,
    day: date,
    counts: dict[Anomaly, int],
    catalog: AccountCatalog,
    tariff: Tariff,
    tz: ZoneInfo,
) -> Dataset:
    builder = _Builder(seed, day, tz, catalog, tariff)
    for anomaly in Anomaly:  # fixed order, so the seed alone determines the output
        for _ in range(counts.get(anomaly, 0)):
            if anomaly is Anomaly.DUPLICATE_INSTRUCTION:
                first, first_id = builder.transfer(Anomaly.CLEAN)
                builder.transfer(anomaly, clone_of=first, related=first_id)
            else:
                builder.transfer(anomaly)
    rates = [
        RateQuote(from_currency=a, to_currency=b, rate_date=day, rate=r, source="recorded")
        for (a, b), r in sorted(RECORDED_RATES.items())
    ]
    return Dataset(seed, day, builder.entries, builder.labels, rates)
